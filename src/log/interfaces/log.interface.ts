export interface LogMetadata {
  [key: string]: any;
  entityId?: number | string;
  entityIds?: (number | string)[];
  oldValues?: Record<string, any>;
  newValues?: Record<string, any>;
  changedFields?: string[];
  errorCode?: string;
  errorMessage?: string;
  duration?: number;
  requestSize?: number;
  responseSize?: number;
  userAgent?: string;
  referer?: string;
  method?: string;
  url?: string;
  statusCode?: number;
  query?: Record<string, any>;
  body?: Record<string, any>;
}

export interface CreateLogDto {
  userId?: number;
  action: LogAction;
  module: LogModule;
  level: LogLevel;
  description: string;
  ipAddress?: string;
  metadata?: LogMetadata;
}

export interface LogEntry {
  id: number;
  userId?: number | null;
  action: string;
  module: string;
  level: string;
  description?: string | null;
  ipAddress?: string | null;
  metadata?: any;
  createdAt: Date;
  user?: {
    id: number;
    username: string;
    email: string;
  } | null;
}

export interface LogStats {
  totalLogs: number;
  logsToday: number;
  logsByModule: Record<string, number>;
  logsByAction: Record<string, number>;
  logsByLevel: Record<string, number>;
  topUsers: Array<{
    userId: number | null;
    userName: string;
    count: number;
  }>;
  recentErrors: LogEntry[];
  systemHealth: {
    errorRate: number;
    averageResponseTime: number;
    status: 'healthy' | 'warning' | 'critical';
  };
}
